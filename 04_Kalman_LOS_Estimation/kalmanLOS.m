function [estimatedAngle, estimatedRate, innovation, kalmanGain] = ...
    kalmanLOS(measuredAngle)

% =========================================================
% 1D CONSTANT VELOCITY KALMAN FILTER
%
% State:
%
% x(1) = LOS angle        [deg]
% x(2) = LOS angular rate [deg/s]
% =========================================================


% ---------------------------------------------------------
% SAMPLE TIME
% ---------------------------------------------------------

Ts = 0.02;


% ---------------------------------------------------------
% PERSISTENT STATES
% ---------------------------------------------------------

persistent x
persistent P


% ---------------------------------------------------------
% INITIALIZATION
% ---------------------------------------------------------

if isempty(x)

    x = [0; 0];

    P = [4 0;
         0 4];

end


% =========================================================
% SYSTEM MODEL
% =========================================================

A = [1 Ts;
     0 1];

H = [1 0];


% ---------------------------------------------------------
% PROCESS NOISE
% ---------------------------------------------------------

Q = [0.001  0;
     0      0.03];


% ---------------------------------------------------------
% MEASUREMENT NOISE VARIANCE
% ---------------------------------------------------------

R = 0.5;


% =========================================================
% PREDICTION
% =========================================================

xPred = A*x;

PPred = A*P*A' + Q;


% =========================================================
% MEASUREMENT UPDATE
% =========================================================

innovation = ...
    measuredAngle - H*xPred;


S = ...
    H*PPred*H' + R;


K = ...
    PPred*H' / S;


x = ...
    xPred + K*innovation;


I = eye(2);

P = ...
    (I - K*H)*PPred;


% =========================================================
% OUTPUTS
% =========================================================

estimatedAngle = x(1);

estimatedRate = x(2);

kalmanGain = K(1);

end